#!/usr/bin/env bash
# Keep this installation in one generator-managed boot menu group.
set -euo pipefail
export LC_ALL=C
ESP=${MAINSTREAM_ESP-}
[[ -n $ESP ]] || ESP=$(source /usr/lib/limine/limine-common-functions \
    && load_config && printf '%s' "$ESP_PATH")
CONF=$ESP/limine.conf
MACHINE_ID=${MAINSTREAM_MACHINE_ID:-$(cat /etc/machine-id)}
MACHINE_ID=${MACHINE_ID,,}
LOCK=${MAINSTREAM_BOOT_LOCK:-/run/lock/boot-partition.lock}
[[ -n $ESP && -f $CONF && $MACHINE_ID =~ ^[0-9a-f]{32}$ ]] || exit 0

mkdir -p "${LOCK%/*}"
exec 9>"$LOCK"
flock -w 60 9 || { echo "The boot partition stayed busy; the boot menu was not updated." >&2; exit 1; }
tmp=$(mktemp "$CONF.mainstream-XXXXXX")
trap 'rm -f "$tmp"' EXIT
python3 - "$CONF" "$MACHINE_ID" >"$tmp" <<'PYTHON'
from pathlib import Path
import re
import sys

lines = Path(sys.argv[1]).read_text().splitlines(keepends=True)
machine = sys.argv[2]
heading = re.compile(r"^[ \t]*(/+)([^/].*)$")
marker = re.compile(r"^[ \t]*comment:[ \t]*machine-id=" + machine + r"(?:[ \t]|$)", re.I)
starts = [i for i, line in enumerate(lines) if (m := heading.match(line.rstrip("\n"))) and len(m[1]) == 1]
if not starts:
    sys.stdout.writelines(lines)
    sys.exit(0)

entries = []
for start, end in zip(starts, starts[1:] + [len(lines)]):
    block = lines[start:end]
    depth = 1
    marked = False
    paths = set()
    own_path = False
    boot_entries = [[]]
    for line in block[1:]:
        if m := heading.match(line.rstrip("\n")):
            depth = len(m[1])
            if depth <= 2:
                boot_entries.append([])
        if depth == 1 and marker.match(line):
            marked = True
        if depth > 2:
            continue
        if m := re.match(r"^[ \t]*(?:path|kernel_path|module_path|image_path):[ \t]*(.*)", line, re.I):
            path = m[1].split("#", 1)[0].strip()
            paths.add(path.lower())
            own_path |= bool(re.match(r"^\$?boot\(\):/+(?:" + machine + r"/|efi/linux/" + machine + r"_)", path, re.I))
        if m := re.match(r"^[ \t]*([\w]+):[ \t]*(.*)", line):
            key, value = m[1].lower(), m[2].strip()
            if key == "comment":
                continue
            key = {"kernel_cmdline": "cmdline", "kernel_path": "path"}.get(key, key)
            if key in ("path", "module_path", "image_path"):
                value = value.split("#", 1)[0].lower()
            boot_entries[-1].append((key, value))
    # Compare each live entry separately, keeping complete command lines and
    # repeated module ordering. A rescue option can use the same kernel files.
    signature = sorted(tuple(sorted(options, key=lambda option: option[0])) for options in boot_entries if options)
    entries.append(dict(start=start, end=end, block=block, marked=marked, paths=paths, own=own_path, signature=signature))

candidates = [entry for entry in entries if entry["own"] or entry["marked"]]
managed = [entry for entry in candidates if entry["marked"]]
if not candidates:
    sys.stdout.writelines(lines)
    sys.exit(0)
if len(managed) == 1:
    keep = managed[0]
elif len(candidates) == 1:
    keep = candidates[0]
else:
    sys.exit("Cannot identify a single boot menu group for this installation; no entries were changed.")

# Remove a duplicate only when all of its live boot settings match.
# Snapshot menus are regenerated by the snapshot service; their files stay put.
drop = {entry["start"] for entry in candidates if entry is not keep and entry["own"] and entry["paths"] == keep["paths"] and entry["signature"] == keep["signature"]}
header = [line for line in lines[:starts[0]] if not marker.match(line)]
sys.stdout.writelines(header)
# Keep the installation in its original menu position so numeric defaults
# still select it when an obsolete group preceded the generated one.
position = min({keep["start"]} | drop)
for entry in entries:
    if entry["start"] != position:
        if entry is not keep and entry["start"] not in drop:
            sys.stdout.writelines(entry["block"])
        continue
    block = keep["block"]
    sys.stdout.write("/+Mainstream OS" + "\\" * 2 + "\n")
    # Keep existing generator metadata, including ordering, in the parent.
    parent_end = next((i for i, line in enumerate(block[1:], 1) if heading.match(line.rstrip("\n"))), len(block))
    existing = next((line for line in block[1:parent_end] if marker.match(line)), None)
    sys.stdout.write(existing if existing else "comment: machine-id=" + machine + "\n")
    sys.stdout.writelines(line for line in block[1:parent_end] if not marker.match(line))
    sys.stdout.writelines(block[parent_end:])
PYTHON

cmp -s "$CONF" "$tmp" && exit 0
backup="$CONF.mainstream-backup-$(date -u +%Y%m%dT%H%M%S%N)"
cp -p "$CONF" "$backup"
sync -f "$backup"
if command -v limine-reset-enroll >/dev/null 2>&1; then
    limine-reset-enroll
fi
chmod 644 "$tmp"
sync -f "$tmp"
mv -f "$tmp" "$CONF"
sync -f "$CONF"
if command -v limine-enroll-config >/dev/null 2>&1; then
    limine-enroll-config
fi
echo "Updated this installation's boot menu group; previous menu saved to $backup."
